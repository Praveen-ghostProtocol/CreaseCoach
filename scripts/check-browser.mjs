import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import { mkdir, readFile } from 'node:fs/promises';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.CREASE_BROWSER_PACKAGE || 'playwright');
const executablePath = process.env.CREASE_BROWSER_EXE;
const output = process.env.CREASE_SCREENSHOTS || '.browser-test';
await mkdir(output,{recursive:true});
const server = spawn(process.execPath,['scripts/serve.mjs','--dist','--port','0'],{windowsHide:true,stdio:['ignore','pipe','pipe']});
let browser;
let desktop;
try {
  const base = await new Promise((resolve,reject) => {
    const timeout = setTimeout(()=>reject(new Error('Preview timed out')),6000);
    server.once('error',reject);
    server.once('exit',code=>reject(new Error(`Preview exited ${code}`)));
    server.stdout.once('data',chunk=>{
      clearTimeout(timeout);
      const port = /localhost:(\d+)/.exec(String(chunk))?.[1];
      if (port) resolve(`http://127.0.0.1:${port}`);
      else reject(new Error(`Unexpected preview status: ${String(chunk)}`));
    });
  });
  const launch = {executablePath,args:['--enable-unsafe-swiftshader']};
  desktop = await chromium.launchPersistentContext('',{...launch,viewport:{width:1440,height:980},reducedMotion:'reduce'});
  const context = desktop;
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if (message.type()==='error') errors.push(message.text());});
  const check = async (locator,re,message) => assert.match(await locator.innerText(),re,message);
  const dialog = page.getByRole('dialog');
  const heading = text => page.getByRole('heading',{name:text,exact:true}).waitFor();
  const nav = label => page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:label,exact:true}).click();

  await page.goto(base);
  await heading('Welcome back, Arjun.');
  await check(page.locator('.stat-grid'),/158/,'Demo total');
  const placement = await page.evaluate(()=>{
    const shell=document.querySelector('.main-shell'), side=document.querySelector('.sidebar');
    return {main:shell.getBoundingClientRect().left,edge:side.getBoundingClientRect().right,margin:getComputedStyle(shell).marginLeft,viewport:innerWidth,side:getComputedStyle(shell).getPropertyValue('--side')};
  });
  assert.ok(placement.main>=placement.edge,JSON.stringify(placement));
  await page.screenshot({path:`${output}/creasecoach-desktop.png`,fullPage:true});
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(()=>document.activeElement.textContent.trim()),'Skip to content');
  await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'content');
  await page.getByRole('button',{name:'Guided demo'}).click();
  await check(page.getByRole('region',{name:'Guided demo'}),/Demo step 1 of 5/);
  await page.getByRole('button',{name:'Next step'}).click();
  await heading('Innings log');
  await page.getByRole('button',{name:'Close guided demo'}).click();
  console.log('PASS home, keyboard skip and guided demo');

  await page.getByRole('button',{name:'Log an innings',exact:true}).click();
  await dialog.getByLabel('Runs',{exact:true}).fill('28');
  await dialog.getByLabel('Balls faced').fill('22');
  await dialog.getByLabel('Outcome').selectOption('yes');
  await dialog.getByLabel('Dismissal type').selectOption('Caught');
  await dialog.getByRole('button',{name:'Save innings'}).click();
  assert.equal(await page.locator('tbody tr').count(),7);
  await nav('Performance Insights');
  await check(page.locator('.evidence-grid'),/4 of 6 recorded dismissals were caught/);
  await page.getByRole('button',{name:'Inspect supporting innings'}).click();
  await heading('Innings log');
  assert.equal(await page.locator('tbody tr').count(),4);
  await page.locator('tbody tr').first().getByRole('button',{name:'Edit innings'}).click();
  await dialog.getByLabel('Outcome').selectOption('no');
  await dialog.getByRole('button',{name:'Save innings'}).click();
  await page.getByRole('button',{name:'Clear filters'}).click();
  await page.locator('tbody tr').filter({has:page.locator('td strong').filter({hasText:/^28\*?$/})}).getByRole('button',{name:'Delete innings'}).click();
  await dialog.getByRole('button',{name:'Delete innings'}).click();
  assert.equal(await page.locator('tbody tr').count(),6);
  await nav('Performance Insights');
  await check(page.locator('.evidence-grid'),/3 of 5 recorded dismissals were caught/);
  await page.getByLabel('Your assessment').selectOption('Ask a coach');
  await check(page.locator('.feedback-row p'),/Show the supporting innings/);
  console.log('PASS innings creation, edit, deletion, denominators, drill-down and feedback');

  await page.getByRole('button',{name:'Bat Motion Explorer'}).click();
  await page.locator('.motion-indicator').waitFor();
  await check(page.locator('.motion-indicator'),/WebGL/);
  const motion = page.locator('.motion-stage');
  const initial = await motion.screenshot();
  await page.getByRole('button',{name:'Elevated'}).click();
  assert.notDeepEqual(await motion.screenshot(),initial);
  await page.getByLabel('Motion sample').selectOption('motion-b');
  await check(page.locator('#motion-metrics'),/0\.88 s/);
  await page.getByLabel('Overlay the other session').check();
  await page.getByRole('button',{name:'Play swing'}).click();
  await page.waitForFunction(()=>Number(document.querySelector('#motion-progress').value)>.05);
  await page.getByRole('button',{name:'Pause swing'}).click();
  await page.getByLabel('Include simulated comparison in plan').check();
  const box = await motion.boundingBox();
  const beforeDrag = await motion.screenshot();
  await page.mouse.move(box.x+box.width*.56,box.y+box.height*.5);
  await page.mouse.down();
  await page.mouse.move(box.x+box.width*.63,box.y+box.height*.58,{steps:6});
  await page.mouse.up();
  assert.notDeepEqual(await motion.screenshot(),beforeDrag);
  await page.screenshot({path:`${output}/creasecoach-motion.png`,fullPage:true});
  console.log('PASS WebGL, camera presets, drag orbit, comparison, playback and evidence selection');

  await nav('Video Lab');
  await page.getByRole('button',{name:'Approximate contact',exact:true}).click();
  await check(page.locator('#video-time'),/0:03\.0/);
  await page.getByRole('button',{name:'Freeze and capture frame'}).click();
  await dialog.getByRole('img',{name:'Captured local playback frame'}).waitFor();
  await dialog.getByRole('button',{name:'Add observation'}).click();
  await dialog.getByLabel('What did you notice?').fill('Fictional test observation at contact.');
  await dialog.getByLabel('Use in practice plan').check();
  await dialog.getByRole('button',{name:'Save observation'}).click();
  const note = page.locator('.notes-list li').filter({hasText:'Fictional test observation'});
  await note.getByRole('button',{name:'Edit observation'}).click();
  await dialog.getByLabel('What did you notice?').fill('Edited fictional observation at contact.');
  await dialog.getByRole('button',{name:'Save observation'}).click();
  await page.getByText('Edited fictional observation at contact.',{exact:true}).waitFor();

  const media=await readFile(new URL('../test/fixtures/local-review.webm',import.meta.url));
  await page.locator('#video-file').setInputFiles({name:'fixture.webm',mimeType:'video/webm',buffer:media});
  await page.locator('#video-element').waitFor({timeout:15000});
  await page.waitForFunction(()=>document.querySelector('video')?.readyState>=2);
  await page.getByLabel('Playback speed',{exact:true}).selectOption('.5');
  await page.getByRole('button',{name:'Play',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('video')?.currentTime>.1);
  await page.getByRole('button',{name:'Freeze and capture frame'}).click();
  await dialog.getByRole('img',{name:'Captured local playback frame'}).waitFor();
  assert.match(await dialog.getByRole('img').getAttribute('src'),/^data:image\/png/);
  await dialog.getByRole('button',{name:'Close dialog'}).click();
  await page.reload();
  await page.getByLabel('Clip or storyboard').selectOption({label:'fixture.webm'});
  await heading('Reselect the local file');
  console.log('PASS storyboard and local WebM playback, frame capture, annotation editing and media reselection');

  await nav('Next Session Plan');
  await check(page.locator('.desktop-evidence .evidence-list'),/Edited fictional observation/);
  await check(page.locator('.desktop-evidence .evidence-list'),/Bat Motion Explorer/);
  await page.getByLabel('Practice focus').selectOption('contact');
  await check(page.locator('.plan-activities'),/Controlled contact check/);
  await page.getByLabel('One improvement objective').fill('Compare my contact notes across six controlled feeds.');
  await page.getByRole('button',{name:'Save practice plan'}).click();
  await page.getByLabel('Activity completed').first().check();
  await page.getByLabel('Post-session reflection').fill('Used the same feed for six attempts.');
  await page.getByLabel('Mark session complete').check();
  await page.getByRole('button',{name:'Save changes'}).click();
  await page.reload();
  await page.getByRole('button',{name:/Contact consistency.*Completed/}).click();
  assert.equal(await page.getByLabel('One improvement objective').inputValue(),'Compare my contact notes across six controlled feeds.');
  assert.equal(await page.getByLabel('Post-session reflection').inputValue(),'Used the same feed for six attempts.');
  assert.ok(await page.getByLabel('Activity completed').first().isChecked());
  await page.getByRole('button',{name:'Demo workspace',exact:true}).click();
  await dialog.getByRole('button',{name:'Start with my own records'}).click();
  await heading('Welcome back, Player.');
  assert.match(await page.locator('.stat').first().innerText(),/\b0\b/);
  await page.getByRole('button',{name:'Log an innings'}).click();
  await dialog.getByLabel('Runs',{exact:true}).fill('8');
  await dialog.getByLabel('Balls faced').fill('10');
  await dialog.getByRole('button',{name:'Save innings'}).click();
  await page.getByRole('button',{name:'My workspace',exact:true}).click();
  const download = page.waitForEvent('download');
  await dialog.getByRole('button',{name:'Export records'}).click();
  const backup = await readFile(await (await download).path());
  const exported = JSON.parse(backup);
  assert.equal(exported.workspace.innings.length,1);
  assert.equal(exported.workspace.innings[0].runs,8);
  exported.workspace.innings[0].runs=12;
  await page.locator('#backup-file').setInputFiles({name:'personal-test.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(exported))});
  await dialog.getByRole('button',{name:'Import backup'}).click();
  await check(page.locator('.stat').nth(1),/\b12\b/);
  await page.getByRole('button',{name:'My workspace',exact:true}).click();
  await dialog.getByRole('button',{name:'Explore demo player'}).click();
  await heading('Welcome back, Arjun.');
  await page.getByRole('button',{name:'Demo workspace',exact:true}).click();
  await dialog.getByRole('button',{name:'Reset demo records'}).click();
  await dialog.getByRole('button',{name:'Reset demo',exact:true}).click();
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('creasecoach.workspace')).demo.plans.length),1);
  console.log('PASS plan persistence, workspace isolation, personal export/import and demo reset');

  await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
  const session = await context.newCDPSession(page);
  await session.send('Page.enable');
  const manifest = await session.send('Page.getAppManifest');
  assert.equal(manifest.errors.length,0);
  assert.equal(manifest.parsed.scope,`${base}/`);
  const {installabilityErrors} = await session.send('Page.getInstallabilityErrors');
  assert.deepEqual(installabilityErrors,[]);
  await context.setOffline(true);
  await page.reload();
  await heading('Welcome back, Arjun.');
  await nav('Performance Insights');
  await page.getByRole('button',{name:'Bat Motion Explorer'}).click();
  await page.locator('.motion-indicator').waitFor();
  await context.setOffline(false);
  assert.deepEqual(errors,[]);
  console.log('PASS service worker, manifest, Chromium installability and offline reload including the lazy explorer');

  browser = await chromium.launch(launch);
  const mobile = await browser.newPage({viewport:{width:375,height:812},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  const mobileErrors=[];
  mobile.on('pageerror',error=>mobileErrors.push(error.message));
  await mobile.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function(kind,...args){return kind==='webgl' ? null : original.call(this,kind,...args);};
  });
  for (const path of ['home','log','insights','video','plan']) {
    await mobile.goto(`${base}/#${path}`);
    await mobile.locator('h1').waitFor();
    const dims = await mobile.evaluate(()=>[document.documentElement.scrollWidth,innerWidth]);
    assert.ok(dims[0]<=dims[1],`${path} overflow: ${dims.join('/')}`);
  }
  await mobile.getByText('Review current evidence',{exact:false}).click();
  await check(mobile.locator('.mobile-evidence'),/3 of 5 recorded dismissals were caught/);
  await mobile.getByText('Review current evidence',{exact:false}).click();
  await mobile.screenshot({path:`${output}/creasecoach-mobile-plan.png`,fullPage:true});
  await mobile.getByRole('navigation',{name:'Mobile navigation'}).getByRole('link',{name:'Insights'}).click();
  await mobile.getByRole('button',{name:'Bat Motion Explorer'}).click();
  await check(mobile.locator('.motion-indicator'),/2D fallback/);
  await mobile.getByLabel('Motion sample').selectOption('motion-b');
  await check(mobile.locator('#motion-metrics'),/0\.88 s/);
  await mobile.getByRole('button',{name:'Play swing'}).click();
  await mobile.waitForFunction(()=>Number(document.querySelector('#motion-progress').value)>.05);
  assert.deepEqual(mobileErrors,[]);
  console.log('PASS 375px navigation, all five layouts and forced SVG motion fallback');
} finally {
  await browser?.close();
  await desktop?.close();
  server.kill();
}
